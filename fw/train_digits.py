"""python fw/train_digits.py : train a 64-32-10 MLP on scikit-learn's 8x8 handwritten digits, quantize it to INT8 exactly
the way ZG-NPU computes (int32 accumulate, (acc+bias)*MULT round-shift SHIFT, clamp, ReLU), and write fw/model.h with the
weights, 32 test images, their labels and the bit-exact expected int32 logits. Also writes results/soc/model.json."""
import json
from pathlib import Path
import numpy as np
from sklearn.datasets import load_digits
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier

ROOT = Path(__file__).resolve().parents[1]
NTEST = 16

X, y = load_digits(return_X_y=True)                 # pixels 0..16
Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.25, random_state=7, stratify=y)
clf = MLPClassifier(hidden_layer_sizes=(32,), activation='relu', max_iter=600, random_state=3, alpha=1e-3)
clf.fit(Xtr / 16.0, ytr)
float_acc = clf.score(Xte / 16.0, yte)
W1, W2 = clf.coefs_
b1, b2 = clf.intercepts_

# ---------------- quantization (per-tensor symmetric weights, unsigned-range inputs stored as int8 0..127)
s_x = (1.0 / 16.0) * (16.0 / 127.0)                  # x_float = pixel/16 ; x_q = round(pixel*127/16)
q = lambda a, s: np.clip(np.round(a / s), -127, 127).astype(np.int64)
s_w1 = np.abs(W1).max() / 127.0
s_w2 = np.abs(W2).max() / 127.0
W1q, W2q = q(W1, s_w1), q(W2, s_w2)
b1q = np.round(b1 / (s_x * s_w1)).astype(np.int64)
xq = lambda P: np.clip(np.round(P * 127.0 / 16.0), 0, 127).astype(np.int64)

# hidden activation scale from the training set
h_float = np.maximum(0, (Xtr / 16.0) @ W1 + b1)
s_h = np.percentile(h_float, 99.9) / 127.0
SHIFT = 24
MULT = int(round((s_x * s_w1 / s_h) * (1 << SHIFT)))
b2q = np.round(b2 / (s_h * s_w2)).astype(np.int64)


def npu_requant(acc, bias, mult, shift, zp=0, relu=True):
    v = (acc + bias).astype(object) * mult
    v = (v + (1 << (shift - 1))) >> shift
    v = v + zp
    return np.clip(np.array(v, dtype=object), zp if relu else -128, 127).astype(np.int64)


def infer(P):
    acc1 = xq(P) @ W1q
    h = npu_requant(acc1, b1q, MULT, SHIFT)
    return h @ W2q + b2q, h


logits_all, _ = infer(Xte)
q_acc = float((logits_all.argmax(1) == yte).mean())
Xs, ys = Xte[:NTEST], yte[:NTEST]
logits, hidden = infer(Xs)
assert np.abs(logits).max() < 2 ** 31 and np.abs(xq(Xs) @ W1q).max() < 2 ** 31

# ---------------- C header
W2pad = np.zeros((32, 16), dtype=np.int64); W2pad[:, :10] = W2q
b2pad = np.zeros(16, dtype=np.int64); b2pad[:10] = b2q


def carr(name, ctype, a, per=16):
    a = np.asarray(a).ravel()
    body = ',\n  '.join(', '.join(str(int(v)) for v in a[i:i + per]) for i in range(0, len(a), per))
    return f'static const {ctype} {name}[{len(a)}] __attribute__((aligned(4))) = {{\n  {body}\n}};\n'


h = ['// generated by fw/train_digits.py - do not edit', '#pragma once', '#include <stdint.h>',
     f'#define NTEST {NTEST}', f'#define L1_MULT {MULT}', f'#define L1_SHIFT {SHIFT}',
     f'// float accuracy {float_acc:.4f}, int8 accuracy {q_acc:.4f} on {len(yte)} test digits', '']
h.append(carr('X_TEST', 'int8_t', xq(Xs)))            # [NTEST][64]
h.append(carr('W1', 'int8_t', W1q))                   # [64][32]
h.append(carr('B1', 'int32_t', b1q))                  # [32]
h.append(carr('W2', 'int8_t', W2pad))                 # [32][16]  (cols 10..15 zero)
h.append(carr('B2', 'int32_t', b2pad))                # [16]
h.append(carr('LABELS', 'uint8_t', ys))
h.append(carr('EXP_PRED', 'uint8_t', logits.argmax(1)))
h.append(carr('EXP_LOGITS', 'int32_t', logits))       # [NTEST][10]
h.append(carr('EXP_HIDDEN', 'int8_t', hidden))        # [NTEST][32]
(ROOT / 'fw' / 'model.h').write_text('\n'.join(h))

out = ROOT / 'fw' / 'build'
out.mkdir(parents=True, exist_ok=True)
(out / 'model.json').write_text(json.dumps({
    'dataset': 'sklearn digits 8x8', 'arch': '64-32-10 MLP, ReLU', 'train': len(ytr), 'test': len(yte),
    'float_acc': float_acc, 'int8_acc': q_acc, 'mult': MULT, 'shift': SHIFT,
    'ntest_onchip': NTEST, 'labels': ys.tolist(), 'expected_pred': logits.argmax(1).tolist(),
    'images': Xs.astype(int).tolist()}, indent=1))
print(f'float acc {float_acc:.4f}  int8 acc {q_acc:.4f}  MULT {MULT} SHIFT {SHIFT}')
